#!/usr/bin/env python3
"""Offline Unicode Emoji 17.0 / CLDR 48 compiler. Python standard library only."""
import json
import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / 'data/emoji'

def annotation_data(lang):
    result = {}
    for source in ['annotations', 'annotationsDerived']:
        for node in ET.parse(DATA / f'{source}-{lang}.xml').iter('annotation'):
            cp = node.attrib['cp'].replace('\ufe0f', '')
            item = result.setdefault(cp, {'name': '', 'keywords': ''})
            text = ''.join(node.itertext()).strip()
            if text in ['↑↑↑', '']:
                continue
            item['name' if node.attrib.get('type') == 'tts' else 'keywords'] = text
    return result

en, zh = annotation_data('en'), annotation_data('zh')
groups = []
entries = {}
tones = re.compile('[\U0001f3fb-\U0001f3ff]')
for line in (DATA / 'emoji-test.txt').read_text().splitlines():
    if line.startswith('# group:'):
        category = line.split(': ', 1)[1]
        if category not in groups:
            groups.append(category)
    match = re.match(r'^([0-9A-F ]+)\s*; fully-qualified\s*#\s*\S+ E[0-9.]+ (.*)', line)
    if not match:
        continue
    emoji = ''.join(chr(int(c, 16)) for c in match[1].split())
    key = tones.sub('', emoji).replace('\ufe0f', '')
    record = entries.setdefault(key, {'variants': [], 'group': groups.index(category), 'name': match[2]})
    record['variants'].append(emoji)

rows = []
for key, item in entries.items():
    english = en.get(key, {})
    chinese = zh.get(key, {})
    rows.append('\t'.join(['\x1f'.join(item['variants']), str(item['group']), english.get('name') or item['name'], chinese.get('name') or '', english.get('keywords') or '', chinese.get('keywords') or '']))
output = '// Generated by scripts/generate-emoji-catalog.py. Unicode-3.0; see data/emoji/LICENSE.\n'
output += 'export const EMOJI_GROUPS = ' + json.dumps(groups, ensure_ascii=False) + ';\n'
output += 'export const EMOJI_CATALOG = ' + json.dumps('\n'.join(rows), ensure_ascii=False) + ';\n'
(ROOT / 'src/icon-picker/emoji-data.ts').write_text(output)
print(f'{len(rows)} base records; {sum(len(e["variants"]) for e in entries.values())} fully-qualified sequences; {len(output.encode())} bytes')
